def require_file(path):
    """
    Ensure a required file exists.
    """

    if not path.exists():
        raise FileNotFoundError(
            f"Required file not found:\n{path}"
        )


# ============================================================
# LOAD PYTHON KPI RESULTS
# ============================================================

def load_python_results():
    """
    Load KPI results generated by kpi_calculations.py.
    """

    path = REPORT_DIR / "kpi_results.csv"

    require_file(path)

    df = pd.read_csv(path)

    required_columns = [
        "kpi_name",
        "kpi_value",
        "kpi_hierarchy",
    ]

    missing = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            "Python KPI results missing columns: "
            + ", ".join(missing)
        )

    # --------------------------------------------------------
    # Check duplicate KPI names
    # --------------------------------------------------------

    duplicates = df["kpi_name"].duplicated()

    if duplicates.any():

        duplicate_names = (
            df.loc[
                duplicates,
                "kpi_name"
            ]
            .tolist()
        )

        raise ValueError(
            "Duplicate KPI names found in "
            "Python results:\n"
            + "\n".join(duplicate_names)
        )

    # --------------------------------------------------------
    # Check missing approved KPIs
    # --------------------------------------------------------

    available_kpis = set(df["kpi_name"])

    missing_kpis = [
        kpi
        for kpi in EXPECTED_KPIS
        if kpi not in available_kpis
    ]

    if missing_kpis:

        raise ValueError(
            "Missing Python KPI(s):\n"
            + "\n".join(missing_kpis)
        )

    return df


