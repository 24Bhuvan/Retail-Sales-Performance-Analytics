# EXECUTE SQL
# ============================================================

def calculate_sql_kpis():
    """
    Execute all 32 SQL KPI calculations in ONE PostgreSQL call.

    PostgreSQL will therefore request the password only once.
    """

    psql = Path(PSQL_PATH)

    if not psql.exists():

        raise FileNotFoundError(
            "PostgreSQL psql executable not found:\n"
            f"{PSQL_PATH}"
        )

    command = [
        PSQL_PATH,
        "-U",
        DB_USER,
        "-d",
        DATABASE,
        "-A",
        "-t",
        "-F",
        "|",
        "-c",
        SQL_QUERY,
    ]

    print(
        "\nExecuting SQL validation query..."
    )

    completed = subprocess.run(
        command,
        capture_output=True,
        text=True,
    )

    if completed.returncode != 0:

        raise RuntimeError(
            "SQL execution failed:\n"
            + completed.stderr.strip()
        )

    results = {}

    for line in completed.stdout.splitlines():

        line = line.strip()

        if not line:
            continue

        parts = line.split("|", 1)

        if len(parts) != 2:
            continue

        kpi_name = parts[0].strip()
        raw_value = parts[1].strip()

        if (
            raw_value == ""
            or raw_value.lower() == "null"
        ):

            value = np.nan

        else:

            try:

                value = float(raw_value)

            except ValueError as exc:

                raise ValueError(
                    f"Invalid SQL value for "
                    f"{kpi_name}: {raw_value}"
                ) from exc

        results[kpi_name] = value

    # --------------------------------------------------------
    # Check missing SQL KPIs
    # --------------------------------------------------------

    missing = [
        kpi
        for kpi in EXPECTED_KPIS
        if kpi not in results
    ]

    if missing:

        raise ValueError(
            "SQL result missing KPI(s):\n"
            + "\n".join(missing)
        )

    # --------------------------------------------------------
    # Check unexpected SQL KPIs
    # --------------------------------------------------------

    unexpected = [
        kpi
        for kpi in results
        if kpi not in EXPECTED_KPIS
    ]

    if unexpected:

        raise ValueError(
            "Unexpected SQL KPI(s):\n"
            + "\n".join(unexpected)
        )

    return results


# ============================================================
# NUMERIC DIFFERENCE
# ============================================================

def numeric_difference(
    sql_value,
    python_value
):
    """
    Calculate absolute difference.
    """

    if (
        pd.isna(sql_value)
        and pd.isna(python_value)
    ):

        return np.nan

    if (
        pd.isna(sql_value)
        or pd.isna(python_value)
    ):

        return np.nan

    return abs(
        float(sql_value)
        -
        float(python_value)
    )


# ============================================================
# VALUE MATCH
# ============================================================

def values_match(
    sql_value,
    python_value
):
    """
    Determine whether SQL and Python values match
    within controlled tolerance.
    """

    # Both NULL / NaN.
    if (
        pd.isna(sql_value)
        and pd.isna(python_value)
    ):

        return True

    # Only one NULL / NaN.
    if (
        pd.isna(sql_value)
        or pd.isna(python_value)
    ):

        return False

    return bool(
        np.isclose(
            float(sql_value),
            float(python_value),
            atol=ABSOLUTE_TOLERANCE,
            rtol=RELATIVE_TOLERANCE,
        )
    )


# ============================================================
# CREATE VALIDATION REPORT
# ============================================================

def create_validation_report(
    python_results,
    sql_results
):
    """
    Compare all SQL and Python KPI values.
    """

    rows = []

    python_lookup = (
        python_results
        .set_index(
            "kpi_name"
        )[
            "kpi_value"
        ]
        .to_dict()
    )

    for kpi_name in EXPECTED_KPIS:

        python_value = pd.to_numeric(
            python_lookup[kpi_name],
            errors="coerce"
        )

        sql_value = sql_results[
            kpi_name
        ]

        difference = numeric_difference(
            sql_value,
            python_value
        )

        status = (
            "PASS"
            if values_match(
                sql_value,
                python_value
            )
            else "FAIL"
        )

        rows.append(
            [
                kpi_name,
                sql_value,
                python_value,
                difference,
                status,
            ]
        )

    return pd.DataFrame(
        rows,
        columns=[
            "KPI Name",
            "SQL Result",
            "Python Result",
            "Absolute Difference",
            "Validation Status",
        ]
    )


# ============================================================
# VALIDATE REPORT
# ============================================================

def validate_report(validation):
    """
    Validate all 32 KPI comparisons.
    """

    expected_count = len(
        EXPECTED_KPIS
    )

    if len(validation) != expected_count:

        raise ValueError(
            f"Expected {expected_count} "
            f"validation rows, "
            f"found {len(validation)}."
        )

    failed = validation[
        validation[
            "Validation Status"
        ] != "PASS"
    ]

    if not failed.empty:

        print(
            "\nWARNING: KPI validation failures detected:"
        )

        print(
            failed.to_string(
                index=False
            )
        )

        raise ValueError(
            f"{len(failed)} KPI "
            f"validation(s) failed."
        )


